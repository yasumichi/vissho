"""Phase 3: Consistency reviewer and refinement engine."""

from typing import Any
from pydantic import BaseModel, ConfigDict

from vissho.config import VisshoConfig
from vissho.core.schema import create_curriculum_plan_model
from vissho.core.validator import ValidationReport, validate_curriculum_plan
from vissho.llm.client import (
    LLMClientProtocol,
    OllamaClient,
    render_consistency_review_prompt,
)


class ReviewResult(BaseModel):
    """Result of Phase 3 review containing the final curriculum plan and validation report."""

    model_config = ConfigDict(arbitrary_types_allowed=True)

    curriculum_plan: Any
    validation_report: ValidationReport
    refined: bool


class ConsistencyReviewer:
    """Reviewer engine for Phase 3: checking deterministic rules and performing instructional refinement with LLM."""

    def __init__(
        self,
        config: VisshoConfig,
        client: LLMClientProtocol | None = None,
        model: str | None = None,
    ) -> None:
        self.config = config
        self.client = client or OllamaClient()
        self.model = model or getattr(self.client, "default_model", OllamaClient.DEFAULT_MODEL)
        self.curriculum_model = create_curriculum_plan_model(self.config.columns)

    def validate(
        self,
        curriculum_plan: BaseModel | dict[str, Any],
        all_slide_numbers: list[int] | set[int] | int | None = None,
    ) -> ValidationReport:
        """Deterministically validate time sums, session counts, and slide references."""
        return validate_curriculum_plan(
            curriculum_plan=curriculum_plan,
            config=self.config,
            all_slide_numbers=all_slide_numbers,
        )

    def review_and_refine(
        self,
        curriculum_plan: BaseModel,
        all_slide_numbers: list[int] | set[int] | int | None = None,
        force_refine: bool = False,
    ) -> ReviewResult:
        """Review curriculum plan against deterministic rules and refine using LLM if needed.

        Args:
            curriculum_plan: The CurriculumPlan generated by Phase 2.
            all_slide_numbers: Optional list/set of all available slide numbers for coverage check.
            force_refine: If True, always perform LLM refinement even if deterministic rules pass.

        Returns:
            ReviewResult containing the refined curriculum plan, the final validation report,
            and whether LLM refinement was performed.
        """
        # 1. Initial deterministic validation
        initial_report = self.validate(curriculum_plan, all_slide_numbers=all_slide_numbers)

        # If already valid and force_refine is False, return immediately
        if initial_report.is_valid and not force_refine:
            return ReviewResult(
                curriculum_plan=curriculum_plan,
                validation_report=initial_report,
                refined=False,
            )

        # 2. Render review & refinement prompt
        prompt = render_consistency_review_prompt(
            prerequisites=self.config.prerequisites,
            columns=self.config.columns,
            curriculum_plan=curriculum_plan,
            validation_report=initial_report,
        )

        # 3. Call LLM for refined curriculum plan
        raw_refined_data = self.client.generate_structured(
            prompt=prompt,
            schema=self.curriculum_model,
            model=self.model,
        )

        # 4. Validate refined output against dynamic schema
        refined_plan = self.curriculum_model.model_validate(raw_refined_data)

        # 5. Deterministic post-processing (sync session total_minutes with row sums)
        for session in getattr(refined_plan, "sessions", []):
            calculated_total = 0
            for row in getattr(session, "rows", []):
                allocated = getattr(row, "allocated_minutes", 0)
                if isinstance(allocated, int):
                    calculated_total += allocated
            if getattr(session, "total_minutes", None) != calculated_total:
                setattr(session, "total_minutes", calculated_total)

        # 6. Final validation
        final_report = self.validate(refined_plan, all_slide_numbers=all_slide_numbers)

        return ReviewResult(
            curriculum_plan=refined_plan,
            validation_report=final_report,
            refined=True,
        )
